def fmt_peaks(curve):
    pk = dyno_estimate.peaks(curve)
    kw = pk["power_w"] / 1000
    return (f"~{kw:,.0f} kW ({kw * 1.341:,.0f} hp) @ {pk['power_rpm']:,.0f} rpm  ·  "
            f"{pk['torque_nm']:,.0f} Nm ({pk['torque_nm'] * 0.7376:,.0f} lb-ft) @ {pk['torque_rpm']:,.0f} rpm")


class DynoChart(tk.Canvas):
    """Torque (Nm, left axis) and power (kW, right axis) against rpm."""

    def __init__(self, parent, **kw):
        super().__init__(parent, background="white", highlightthickness=1,
                         highlightbackground="#ccc", **kw)
        self.curve = None
        self.bind("<Configure>", lambda e: self.draw(self.curve))

    @staticmethod
    def _nice(v):
        if v <= 0:
            return 1.0
        mag = 10 ** math.floor(math.log10(v))
        for m in (1, 2, 2.5, 5, 10):
            if v <= m * mag:
                return m * mag
        return 10 * mag

    def draw(self, curve):
        self.curve = curve
        self.delete("all")
        w, h = max(self.winfo_width(), 300), max(self.winfo_height(), 200)
        if not curve:
            self.create_text(w / 2, h / 2, text="No estimate yet", fill="#888")
            return
        left, right, top, bottom = 70, 70, 20, 45
        rpm = [c[0] for c in curve]
        tq = [max(0.0, c[1]) for c in curve]
        kw = [max(0.0, c[2] / 1000) for c in curve]
        x0, x1 = rpm[0], rpm[-1]
        tq_max = self._nice(max(tq) * 1.1)
        kw_max = self._nice(max(kw) * 1.1)

        def X(r):
            return left + (r - x0) / max(1.0, x1 - x0) * (w - left - right)

        def Y(v, vmax):
            return h - bottom - v / vmax * (h - top - bottom)

        for k in range(6):
            frac = k / 5
            y = h - bottom - frac * (h - top - bottom)
            self.create_line(left, y, w - right, y, fill="#eee")
            self.create_text(left - 6, y, text=f"{tq_max * frac:,.0f}", anchor="e", fill="#1f6fd1")
            self.create_text(w - right + 6, y, text=f"{kw_max * frac:,.0f}", anchor="w", fill="#d1381f")
        step = self._nice((x1 - x0) / 8)
        r = math.ceil(x0 / step) * step
        while r <= x1:
            self.create_line(X(r), top, X(r), h - bottom, fill="#f2f2f2")
            self.create_text(X(r), h - bottom + 12, text=f"{r:,.0f}", fill="#555")
            r += step
        self.create_text((left + w - right) / 2, h - 12, text="engine speed (rpm)", fill="#555")
        self.create_text(14, (top + h - bottom) / 2, text="torque Nm", angle=90, fill="#1f6fd1")
        self.create_text(w - 14, (top + h - bottom) / 2, text="power kW", angle=90, fill="#d1381f")
        self.create_line(left, top, left, h - bottom, w - right, h - bottom, w - right, top, fill="#999")
        self.create_line(*[v for i in range(len(rpm)) for v in (X(rpm[i]), Y(tq[i], tq_max))],
                         fill="#1f6fd1", width=2, smooth=True)
        self.create_line(*[v for i in range(len(rpm)) for v in (X(rpm[i]), Y(kw[i], kw_max))],
                         fill="#d1381f", width=2, smooth=True)
        i_t, i_p = tq.index(max(tq)), kw.index(max(kw))
        for i, vals, vmax, col in ((i_t, tq, tq_max, "#1f6fd1"), (i_p, kw, kw_max, "#d1381f")):
            x, y = X(rpm[i]), Y(vals[i], vmax)
            self.create_oval(x - 4, y - 4, x + 4, y + 4, fill=col, outline="")


