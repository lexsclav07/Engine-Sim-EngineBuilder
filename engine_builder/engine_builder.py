class Scrollable(ttk.Frame):
    def __init__(self, parent):
        super().__init__(parent)
        self.canvas = canvas = tk.Canvas(self, highlightthickness=0)
        vs = ttk.Scrollbar(self, orient="vertical", command=canvas.yview)
        self.body = ttk.Frame(canvas, padding=8)
        self.body.bind("<Configure>", lambda e: canvas.configure(scrollregion=canvas.bbox("all")))
        canvas.create_window((0, 0), window=self.body, anchor="nw")
        canvas.configure(yscrollcommand=vs.set)
        canvas.pack(side="left", fill="both", expand=True)
        vs.pack(side="right", fill="y")


class TableEditor(ttk.LabelFrame):
    """Grid of entries. columns: list of (title, kind, width) where kind is
    float/int/str/label or ("choice", options)."""

    def __init__(self, parent, title, columns, fixed=False, min_rows=1):
        super().__init__(parent, text=title, padding=6)
        self.columns = columns
        self.fixed = fixed
        self.min_rows = min_rows
        self.rows = []
        self.col_state = {}
        self.grid_frame = ttk.Frame(self)
        self.grid_frame.pack(anchor="w")
        for c, (t, _, w) in enumerate(columns):
            ttk.Label(self.grid_frame, text=t, font=("Segoe UI", 9, "bold")).grid(
                row=0, column=c, padx=2, sticky="w")
        if not fixed:
            bf = ttk.Frame(self)
            bf.pack(anchor="w", pady=(4, 0))
            ttk.Button(bf, text="+ Add row", command=self.add_row).pack(side="left")
            ttk.Button(bf, text="- Remove last row", command=self.remove_row).pack(side="left", padx=4)

    def _make_cell(self, r, c, value):
        title, kind, width = self.columns[c]
        var = tk.StringVar(value=fmt_value(value))
        if kind == "label":
            w = ttk.Label(self.grid_frame, textvariable=var, width=width)
        elif isinstance(kind, tuple):
            w = ttk.Combobox(self.grid_frame, textvariable=var, values=kind[1],
                             width=width, state="readonly")
        else:
            w = ttk.Entry(self.grid_frame, textvariable=var, width=width)
            if self.col_state.get(c) == "disabled":
                w.configure(state="disabled")
        w.grid(row=r + 1, column=c, padx=2, pady=1, sticky="w")
        return var, w

    def set_rows(self, rows):
        for row in self.rows:
            for _, w in row:
                w.destroy()
        self.rows = []
        for values in rows:
            self._append(values)

    def _append(self, values):
        r = len(self.rows)
        self.rows.append([self._make_cell(r, c, v) for c, v in enumerate(values)])

    def add_row(self):
        if self.rows:
            values = [v.get() for v, _ in self.rows[-1]]
        else:
            values = ["0" for _ in self.columns]
        self._append(values)

    def remove_row(self):
        if len(self.rows) > self.min_rows:
            for _, w in self.rows.pop():
                w.destroy()

    def set_column_state(self, c, state):
        self.col_state[c] = state
        for row in self.rows:
            row[c][1].configure(state=state)

    def get_rows(self):
        out = []
        for r, row in enumerate(self.rows):
            vals = []
            for c, (var, _) in enumerate(row):
                title, kind, _ = self.columns[c]
                if kind == "label":
                    vals.append(var.get())
                    continue
                k = "str" if isinstance(kind, tuple) else kind
                try:
                    vals.append(parse_value(var.get(), k))
                except ValueError:
                    raise ValueError(f"{self.cget('text')}: row {r + 1}, column '{title}' "
                                     f"is not a valid number ({var.get()!r})")
            out.append(vals)
        return out


