def parse_value(text, kind):
    if kind == "float":
        return float(str(text).strip())
    if kind == "int":
        return int(round(float(str(text).strip())))
    if kind == "bool":
        return bool(text)
    return str(text)


def fmt_value(v):
    if isinstance(v, float):
        s = f"{v:.10g}"
        return s
    return str(v)


